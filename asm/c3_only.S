# =============================================================================
# asm/c3_only.S —— 类 3 的【最小复现】: 只把交替序列放进一个紧循环
#
# 为什么要它: branch_bench 里类 3 的分支之间隔着 113 条其它条件分支
#   (类1 内层循环 88 + 类2 8 + 类4/类5 8 + 外层回边 1), 而 BHT 的 GHR 只有 22 位。
#   同一条静态分支的下一次实例要等 113 次预测, 相位信息早就被移出 GHR 了 ——
#   实测 pos1 预测时刻的 GHR 在两个相位下逐位相同 (or==and==3ffe00)。
#
#   但如果只是"间隔太长", 那么把它缩短到 9 次预测 (本条分支 + 同轮 7 条 + 回边),
#   GHR 就完全罩得住, 交替序列应该能被学出来。
#   本用例就是做这个对照: 指令序列与 branch_bench 的类 3 逐条相同, PC 也落在同一个
#   区间 [0x1c0,0x250) 上, 所以 TB 里现成的类 3 分桶/逐条统计原样可用。
#
# 判读:
#   > 60%  -> "间隔太长"成立, BHT 的索引/计数机制本身没问题
#    50%    -> 索引里确实没有相位信息, 是结构性缺陷, 与间隔无关
# =============================================================================

    .section .text.init
    .globl _start

_start:
    jal  x0, reset_vector           # 0x000

    .org 0x008
reset_vector:
    addi x31, x0, 512               # 外层迭代次数
    addi x9,  x0, 0                 # 交替位 (每轮翻转一次)
    addi x10, x0, 0                 # taken 路径的累加器
    jal  x0, class3                 # 0x018 -> 直接进入被测区

# -----------------------------------------------------------------------------
# 与 branch_bench.S 的类 3 完全相同的 8 条分支 (16 字节间隔, 同相位)
# -----------------------------------------------------------------------------
    .org 0x1C0
class3:
    xori x9,  x9, 1                 # 0x1C0
    nop
    nop
    nop
    beq  x9,  x0, c3a0              # 0x1D0
    addi x10, x10, 1                # 0x1D4
c3a0:
    nop
    nop
    beq  x9,  x0, c3a1              # 0x1E0
    addi x10, x10, 1                # 0x1E4
c3a1:
    nop
    nop
    beq  x9,  x0, c3a2              # 0x1F0
    addi x10, x10, 1                # 0x1F4
c3a2:
    nop
    nop
    beq  x9,  x0, c3a3              # 0x200
    addi x10, x10, 1                # 0x204
c3a3:
    nop
    nop
    beq  x9,  x0, c3a4              # 0x210
    addi x10, x10, 1                # 0x214
c3a4:
    nop
    nop
    beq  x9,  x0, c3a5              # 0x220
    addi x10, x10, 1                # 0x224
c3a5:
    nop
    nop
    beq  x9,  x0, c3a6              # 0x230
    addi x10, x10, 1                # 0x234
c3a6:
    nop
    nop
    beq  x9,  x0, c3a7              # 0x240
    addi x10, x10, 1                # 0x244
c3a7:
    nop
    nop

# -----------------------------------------------------------------------------
# 外层回边 (落在 class 0, 与 branch_bench 一致)
# -----------------------------------------------------------------------------
    .org 0x250
loop_ctrl:
    addi x31, x31, -1               # 0x250
    bne  x31, x0, class3            # 0x254

    addi x10, x0, 0                 # a0 = 0 (成功)
    addi x17, x0, 93                # a7 = 93
    ecall
    unimp
