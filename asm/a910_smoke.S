# ===========================================================================
# asm/a910_smoke.S —— A910_cpu (乱序多发射整核) 的最小自检冒烟用例
# ===========================================================================
# 【为什么是"纯直线"】这个用例要跑在 `make a910-run TEST=a910_smoke` 上, 而那个顶层
#   有一个**已知未修**的契约问题会丢指令:
#     `ct_idu_top.sv:332` 的 `idu_accept_num` 只有 2'b00/2'b11 两态, 且**不看**
#     `ifu_idu_ib_inst*_vld`; 而 IBUF 的 `head_q <= head_q + pop_num` 无校验
#     ⇒ IBUF 只装 1~2 条却报 3 时会**跳过/丢指令**。
#   那个窗口出现在**取指流被打断**的时候 (跳转之后 IBUF 半满)。
#   ⇒ 本用例**一条指令都不跳、不访存**, 从头到尾顺序取指 ⇒ 完全绕开那个 bug。
#      跑不过就一定是 TB 或执行单元的问题, 不会是它。
#
# 【自检怎么压进 a0】不分支也能自检: 把"结果"和"期望值"相减, 差写进 a0。
#   a0 == 0 ⟺ 全对。TB 盯 `dbg_commit_reg==5'd10` 抓这个值。
#
# 【为什么末尾还留着 ecall】A910 顶层里 ecall **不会**停机 (C910 的 IDU 把整个
#   SYSTEM 主 opcode 判成非法指令, ct_idu_id_decd.sv:139), 但顺序核的 difftest
#   靠它收尾。留着它, 这个用例在 `make run-all` 的顺序核上也能正常跑完。
# ===========================================================================

.section .text.init
.globl _start

_start:
    # ---- 覆盖 ALU + 乘法 + 除法 (正是最近改过的 MD 通路) ----
    addi x5, x0, 100        # x5 = 100
    addi x6, x0, 7          # x6 = 7
    mul  x7, x5, x6         # x7 = 700
    div  x8, x7, x6         # x8 = 100   (700 / 7)

    addi x9, x0, 100        # x9 = 100 (期望值)
    sub  x10, x8, x9        # a0 = x8 - 100  ⇒ 0 表示全对

    # ---- 退出序列 (顺序核的 difftest 靠 ecall 收尾; A910 的 TB 靠上面那个 a0) ----
    addi x17, x0, 93        # a7 = 93 (exit syscall)
    ecall
    unimp
